#ifndef RFL_PARSER_STATE_HPP
#define RFL_PARSER_STATE_HPP

#include "model/parsed_rule.hpp"

#include <memory>
#include <string>
#include <vector>

struct DataBind;
namespace rulesforge { struct ScriptCatalog; }

// This struct has been simplified to hold only the final results of parsing.
// The temporary state used by a previous action-based rulesforge/parser design has been removed.
// This makes the struct a simple, copyable data container for the AST.

struct SchemaImport {
    std::string path;
    std::string source_name;
    std::size_t line = 0;
    std::size_t column = 0;
};

struct ImportedDataBindSchema {
    std::string path;
    std::shared_ptr<DataBind> codec;
};

struct parser_state {
    std::shared_ptr<rulesforge::ScriptCatalog const> script_catalog;
    // Top-level metadata
    std::string package_name;
    std::vector<std::string> parsed_imports;
    std::vector<SchemaImport> schema_imports;
    std::vector<ImportedDataBindSchema> imported_data_bind_schemas;

    // All successfully parsed top-level items
    std::vector<ParsedRule> parsed_rules;
    std::vector<ParsedQuery> parsed_queries;
    std::vector<ParsedFunction> parsed_functions;
    std::vector<ParsedDeclaration> parsed_declarations;
    std::vector<ParsedEnum> parsed_enums;
    std::vector<ParsedGlobal> parsed_globals;

    // The default copy constructor, copy assignment operator, move constructor,
    // move assignment operator, and destructor are all correctly generated by
    // the compiler for this simplified struct.
};

#endif   // RFL_PARSER_STATE_HPP
